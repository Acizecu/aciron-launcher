const DICTS: Record<Lang, Record<string, string>> = { ru: {}, en: EN, tr: TR };

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isLang(saved)) return saved;
  } catch {

  }

  const nav = navigator.language?.toLowerCase() ?? "";
  if (nav.startsWith("ru")) return "ru";
  if (nav.startsWith("tr")) return "tr";
  return "en";
}

let lang: Lang = detect();

document.documentElement.lang = lang;

const subs = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {

  }
  document.documentElement.lang = next;
  for (const f of subs) f();
  if (isTauri) {
    void getSettings()
      .then((s) => saveSettings({ ...s, language: next }))
      .catch(() => {});
  }
}

export async function syncLangFromSettings(): Promise<void> {
  if (!isTauri) return;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    const s = await getSettings();
    if (isLang(saved)) {
      if (s.language !== saved) await saveSettings({ ...s, language: saved });
      return;
    }
    if (isLang(s.language)) setLang(s.language);
    else await saveSettings({ ...s, language: lang });
  } catch {

  }
}

export function t(ru: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang];
  let out = dict[ru] ?? ru;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

const LOCALES: Record<Lang, string> = { ru: "ru-RU", en: "en-US", tr: "tr-TR" };

export function locale(): string {
  return LOCALES[lang];
}

const FMT_CACHE = new Map<string, Intl.DateTimeFormat>();

export function dtf(opts: Intl.DateTimeFormatOptions = {}): Intl.DateTimeFormat {
  const key = lang + "|" + JSON.stringify(opts);
  let f = FMT_CACHE.get(key);
  if (!f) {
    f = new Intl.DateTimeFormat(locale(), opts);
    FMT_CACHE.set(key, f);
  }
  return f;
}

export function ts(msg: string): string {
  const clean = String(msg).replace(/^Error:\s*/, "").trim();
  const dict = DICTS[lang];
  const whole = dict[clean];
  if (whole) return whole;

  const m = /:\s/.exec(clean);
  if (m && m.index > 0) {
    const head = dict[clean.slice(0, m.index)];
    if (head) return head + clean.slice(m.index);
  }
  return clean;
}

function subscribe(cb: () => void) {
  subs.add(cb);
  return () => subs.delete(cb);
}

export function useLang(): { lang: Lang; t: typeof t } {
  const cur = useSyncExternalStore(
    subscribe,
    () => lang,
    () => lang
  );
  return { lang: cur, t };
}

